// Captures real pieces of the app (mock API) so the option mock-ups use the real UI. Run: node scripts/parts-shot.mjs <outdir>
import { chromium } from 'playwright';
import { startServer } from './serve.mjs';
import { createMock } from './mock.mjs';
const out = process.argv[2];
await startServer(4204);
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
await ctx.route('**/*', (r) => (new URL(r.request().url()).hostname === 'localhost' ? r.fallback() : r.abort()));
await createMock({ log: () => {} }).install(ctx);
const page = await ctx.newPage();
await page.goto('http://localhost:4204/login');
await page.evaluate(async () => {
  const post = (p, method, body) => fetch(`http://mock.local/api${p}`, { method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) }).then((r) => r.json());
  const reg = await post('/auth/register', 'POST', { email: 'maya@example.com', password: 'x', username: 'maya' });
  await post('/users/me', 'PATCH', { onboarding_complete: true, primary_track: 'rebirth', nook_offered_at: '2026-11-03T10:00:00-05:00', nook_enabled: true, pip_introduced: true, hemisphere: 'north', has_pets: false });
  await post('/plants', 'POST', { common_name: 'Spider Plant', nickname: 'Sammy' });
  localStorage.setItem('grove_access_token', reg.access_token);
  localStorage.setItem('grove_refresh_token', reg.refresh_token);
});
const snap = async (loc, name) => { try { await loc.first().screenshot({ path: `${out}/${name}.png` }); console.log('ok', name); } catch (e) { console.log('MISS', name); } };
const clip = async (y, h, name) => { await page.screenshot({ path: `${out}/${name}.png`, clip: { x: 0, y, width: 390, height: h } }); console.log('ok', name); };
const dismissPip = async () => { await page.addStyleTag({ content: '.pip-layer{display:none!important}' }); };
await page.goto('http://localhost:4204/care/today');
await page.getByTestId('care-card').first().waitFor();
await dismissPip(); await page.waitForTimeout(800);
await clip(0, 117, 'header-today');
await snap(page.getByTestId('today-search'), 'today-search');
await snap(page.getByTestId('care-card'), 'plantcard');
await snap(page.getByTestId('reminder-note'), 'reminder');
await snap(page.getByTestId('pip-note'), 'pipnote');
await snap(page.getByTestId('bottom-nav'), 'nav');
await page.goto('http://localhost:4204/nook'); await page.waitForTimeout(2500); await dismissPip();
await page.screenshot({ path: `${out}/nook-top.png`, fullPage: true });
await page.goto('http://localhost:4204/greenhouse'); await page.waitForTimeout(2500); await dismissPip();
await clip(0, 117, 'header-learn');
await snap(page.getByTestId('learn-lessons-card'), 'lessons-card');
await snap(page.getByTestId('greenhouse-search'), 'guide-search');
await snap(page.getByTestId('species-card'), 'species-card');
await page.screenshot({ path: `${out}/learn-full.png`, fullPage: true });
await page.goto('http://localhost:4204/lessons'); await page.waitForTimeout(2500); await dismissPip();
await page.screenshot({ path: `${out}/lessons-full.png`, fullPage: true });
await page.goto('http://localhost:4204/plants'); await page.waitForTimeout(1500); await dismissPip();
await clip(0, 117, 'header-plants');
await b.close(); process.exit(0);
