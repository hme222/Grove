import { chromium } from 'playwright';
import fs from 'node:fs';
import { startServer } from './serve.mjs';
import { createMock, FROZEN_NOW } from './mock.mjs';

const out = process.argv[2];
fs.mkdirSync(out, { recursive: true });
const server = await startServer();
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, hasTouch: false });
const mock = createMock({ log: (m) => console.log('  net', m) });
await mock.install(ctx);
const page = await ctx.newPage();
await page.clock.install({ time: new Date(FROZEN_NOW) });
await page.clock.setFixedTime(new Date(FROZEN_NOW));
page.on('console', (m) => { if (m.type() === 'error') console.log('  console.error', m.text().slice(0, 160), m.location().url); });
page.on('pageerror', (e) => console.log('  pageerror', e.message.slice(0, 160)));
let n = 0;
const snap = async (label) => {
  await page.screenshot({ path: `${out}/${String(++n).padStart(2, '0')}-${label}.png` });
  const ids = await page.$$eval('[data-testid]', (els) => els.filter((e) => e.offsetParent !== null || getComputedStyle(e).position === 'fixed').map((e) => e.getAttribute('data-testid')));
  console.log(`[${n}] ${label} ::`, [...new Set(ids)].join(', '));
};
const step = async (label, fn) => { try { await fn(); } catch (e) { console.log('FAILED', label, e.message.split('\n')[0]); } await page.waitForTimeout(500); await snap(label); };

await page.goto('http://localhost:4173/');
await page.waitForTimeout(1500);
await snap('welcome');
await step('welcome-continue', async () => { await page.mouse.click(195, 400); await page.getByTestId('onboarding-continue').click({ timeout: 3000 }); });
await step('account-fill', async () => { await page.getByTestId('signup-email').fill('maya@example.com'); await page.getByTestId('signup-password').fill('growgrove1'); });
await step('account-submit', async () => { await page.getByTestId('signup-submit').click(); });
for (let i = 0; i < 3; i++) await step(`after-${i + 1}`, async () => { await page.getByTestId('onboarding-continue').click({ timeout: 3000 }); });
await step('hemisphere', async () => { await page.locator('[data-testid^="hemisphere-"]').first().click({ timeout: 3000 }); });
await step('hemisphere-next', async () => { await page.getByTestId('onboarding-continue').click({ timeout: 3000 }); });
await step('quiz-intro-start', async () => { await page.getByTestId('quiz-intro-start').click({ timeout: 3000 }); });
await step('q1-option', async () => { await page.locator('[data-testid^="option-q1"]').first().click({ timeout: 3000 }); });
await step('q1-next', async () => { await page.getByTestId('question-next').click({ timeout: 3000 }); });
for (const q of ['q2', 'q3', 'q4']) await step(`${q}-skip`, async () => { await page.getByTestId('question-skip').click({ timeout: 3000 }); });
await page.waitForTimeout(1500);
await snap('plan');
await step('plan-start', async () => { await page.getByTestId('plan-start').click({ timeout: 4000 }); });
for (let i = 1; i <= 4; i++) await step(`lesson-card-${i}`, async () => { await page.getByTestId('lesson-next').click({ timeout: 4000 }); });
await step('soil-add-plant', async () => { await page.getByTestId('soil-step-add-plant').click({ timeout: 4000 }); });
await step('add-plant-chooser', async () => {});
await step('manual', async () => { await page.getByTestId('add-option-manual').click({ timeout: 4000 }); });
await step('search', async () => { await page.getByTestId('species-search-input').fill('spider'); await page.waitForTimeout(900); });
await step('pick', async () => { await page.getByTestId('species-option').first().click({ timeout: 4000 }); });
console.log('BUTTONS-form:', await page.$$eval('button', (els) => els.filter((e) => e.offsetParent).map((e) => (e.innerText || '').trim().slice(0, 40)).filter(Boolean)));
await step('to-photo', async () => { await page.getByRole('button', { name: /add a photo/i }).click({ timeout: 4000 }); });
await step('skip-photo', async () => { await page.getByTestId('photo-skip').click({ timeout: 4000 }); await page.waitForTimeout(1200); });
await step('learn-tab', async () => { await page.getByRole('link', { name: 'Learn' }).click({ timeout: 4000 }); await page.waitForTimeout(800); });
await step('today-tab', async () => { await page.getByRole('link', { name: 'Today' }).click({ timeout: 4000 }); await page.waitForTimeout(800); });
await step('lesson-resume', async () => { await page.getByTestId('next-lesson-start').scrollIntoViewIfNeeded(); await page.getByTestId('next-lesson-start').click({ timeout: 4000 }); await page.waitForTimeout(800); });
await step('outcome-dry', async () => { await page.getByTestId('soil-outcome-dry').click({ timeout: 4000 }); });
await step('decision-water', async () => { await page.getByTestId('soil-decision-water').click({ timeout: 4000 }); });
await step('submit', async () => { await page.getByTestId('soil-step-submit').click({ timeout: 4000 }); await page.waitForTimeout(800); });
await step('continue', async () => { await page.getByTestId('soil-step-continue').click({ timeout: 4000 }); await page.waitForTimeout(1200); });
await step('celebration-cta', async () => { await page.getByTestId('first-care-celebration-cta').click({ timeout: 4000 }); await page.waitForTimeout(1500); });
await step('offer-yes', async () => { await page.getByTestId('nook-offer-yes').click({ timeout: 4000 }); await page.waitForTimeout(1200); });
await step('today-after', async () => { await page.getByRole('link', { name: 'Today' }).click({ timeout: 4000 }); await page.waitForTimeout(1200); });
await step('pip-thumb', async () => { await page.getByTestId('pip-note-thumb').click({ timeout: 4000 }); await page.waitForTimeout(1500); });
console.log('BUTTONS:', await page.$$eval('button, a', (els) => els.filter((e) => e.offsetParent).map((e) => (e.innerText || '').trim().slice(0, 40)).filter(Boolean)));
await browser.close();
server.close();
console.log('UNMOCKED:', mock.state.unmocked);
